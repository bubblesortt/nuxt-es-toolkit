import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const surfaceSpecifiers = {
  base: 'es-toolkit',
  compat: 'es-toolkit/compat',
  fp: 'es-toolkit/fp',
  map: 'es-toolkit/map',
  set: 'es-toolkit/set',
}

const outputPath = resolve(dirname(fileURLToPath(import.meta.url)), '../src/generated/es-toolkit-exports.ts')
const exportNames = module => Object.keys(module)
  .filter(name => name !== 'default')
  .sort()
const quote = value => `'${value.replaceAll('\\', '\\\\').replaceAll(/'/g, '\\$&')}'`

export const discoverExportCatalogue = async () => {
  const packageJson = await import('es-toolkit/package.json', { with: { type: 'json' } })
  const entries = await Promise.all(Object.entries(surfaceSpecifiers).map(async ([surface, specifier]) => [
    surface,
    exportNames(await import(specifier)),
  ]))
  const surfaces = Object.fromEntries(entries)
  for (const [surface, names] of Object.entries(surfaces)) {
    if (names.length === 0 || new Set(names).size !== names.length) {
      throw new Error(`Invalid ${surface} export surface for es-toolkit ${packageJson.default.version}.`)
    }
  }
  return { version: packageJson.default.version, surfaces }
}

export const renderExportCatalogue = (catalogue) => {
  const lines = [
    '// This file is generated by scripts/export-catalogue.mjs. Do not edit manually.',
    '',
    `export const esToolkitVersion = ${quote(catalogue.version)} as const`,
  ]

  for (const surface of Object.keys(surfaceSpecifiers)) {
    const constantName = `${surface}Exports`
    lines.push('', `export const ${constantName} = [`)
    for (const name of [...catalogue.surfaces[surface]].sort()) {
      lines.push(`  ${quote(name)},`)
    }
    lines.push('] as const')
  }

  return `${lines.join('\n')}\n`
}

const run = async () => {
  const mode = process.argv[2]
  if (mode !== '--write' && mode !== '--check') {
    throw new Error('Usage: node scripts/export-catalogue.mjs --write|--check')
  }

  const output = renderExportCatalogue(await discoverExportCatalogue())
  if (mode === '--write') {
    await mkdir(dirname(outputPath), { recursive: true })
    await writeFile(outputPath, output)
    return
  }

  let committed = ''
  try {
    committed = await readFile(outputPath, 'utf8')
  }
  catch {
    // A missing catalogue is drift and receives the same actionable output.
  }
  if (committed !== output) {
    console.error('es-toolkit export catalogue is out of date. Run: pnpm generate:exports')
    process.exitCode = 1
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await run()
}
